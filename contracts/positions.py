# -*- coding: utf-8 -*-
"""Справочник должностей подписанта заказчика.

В карточке должность вводится в родительном падеже («в лице генерального
директора») — так она нужна преамбуле договора. В блоке подписи и приложениях
нужен именительный падеж («Генеральный директор»); он подбирается по
справочнику ниже. Новую должность добавляет правка POSITIONS и commit.
"""
import re

# Ключ — родительный падеж в нижнем регистре, значение — именительный.
POSITIONS = {
    'генерального директора': 'Генеральный директор',
    'директора': 'Директор',
    'исполнительного директора': 'Исполнительный директор',
    'коммерческого директора': 'Коммерческий директор',
    'финансового директора': 'Финансовый директор',
    'технического директора': 'Технический директор',
    'заместителя генерального директора': 'Заместитель генерального директора',
    'заместителя директора': 'Заместитель директора',
    'временно исполняющего обязанности генерального директора':
        'Временно исполняющий обязанности генерального директора',
    'председателя': 'Председатель',
    'председателя правления': 'Председатель правления',
    'управляющего': 'Управляющий',
    'главы': 'Глава',
    'главы администрации': 'Глава администрации',
    'президента': 'Президент',
    'руководителя': 'Руководитель',
    'индивидуального предпринимателя': 'Индивидуальный предприниматель',
}


def _clean(text) -> str:
    """Строка без лишних пробелов по краям и дублей внутри."""
    return re.sub(r'\s+', ' ', (text or '').strip())


def is_known_position(text) -> bool:
    """True, если должность есть в справочнике (без учёта регистра)."""
    return _clean(text).casefold() in POSITIONS


def signature_position(text) -> str:
    """Должность для блока подписи: именительный падеж из справочника.

    Если должности нет в справочнике, возвращается введённый текст без
    изменений, кроме заглавной первой буквы. Пустой ввод даёт пустую строку.
    """
    raw = _clean(text)
    if not raw:
        return ''
    known = POSITIONS.get(raw.casefold())
    if known:
        return known
    return raw[0].upper() + raw[1:]
