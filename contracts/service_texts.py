"""Формулировки услуг для п. 1.1 договора.

Названия в справочнике тарифов короче, чем текст в договоре, поэтому
для позиций с известным кодом выводится полная формулировка из SERVICE_TEXTS.
Позиция 2.6 («Полный пакет 2.1-2.5», справочная) раскрывается
в пункты 2.1, 2.2, 2.3, 2.4, 2.5 и 3.1 по порядку кодов. Позиции без
текста в SERVICE_TEXTS остаются с названием из справочника.
"""
from . import pricing

PACKAGE_CODE = '2.6'
PACKAGE_CONTENT = pricing.COUNCIL_PACKAGE_CODES + (pricing.SUBMISSION_CODE,)

SERVICE_TEXTS = {
    '2.1': (
        'Подготовка пакета документов для предоставления земельного '
        'участка на Совете по земельным и имущественным отношениям '
        'при Правительстве Нижегородской области.'
    ),
    '2.2': (
        'Подготовка выкопировки земельного участка с указанием '
        'площади и границ земельного участка, адресных ориентиров, '
        'обозначением места размещения объекта в масштабе 1:500 '
        '(для земельных участков площадью более 10 тыс. кв. м - 1:1000 или 1:2000).'
    ),
    '2.3': 'Подготовка расчета нагрузок для сбора технических условий.',
    '2.4': (
        'Подготовка архитектурного решения (с планом размещения '
        'объекта и благоустройством, с указанием основных '
        'параметров объекта).'
    ),
    '2.5': 'Подготовка бизнес-плана.',
    '3.1': (
        'Заполнение ходатайства и направление полного пакета '
        'документов в соответствии с приказом министерства '
        'имущественных и земельных отношений Нижегородской области '
        'от 02.07.2018 № 151-од через портал ГИСОГД НО, методическая '
        'поддержка Заказчика до направления пакета документов на '
        'рассмотрение Совета по земельным и имущественным '
        'отношениям при Правительстве Нижегородской области.'
    ),
}


def _get(row, key):
    """Значение поля строки услуги (Row или dict); None, если поля нет."""
    return row[key] if key in row.keys() else None


def contract_service_items(services) -> list:
    """Список (текст, количество) для п. 1.1 в порядке выбора услуг.

    Позиция 2.6 раскрывается в шесть пунктов. Количество
    указывается только у позиций без полной формулировки
    в SERVICE_TEXTS. Повторы одинакового текста убираются.
    """
    items = []
    seen = set()

    def add(text, qty=None):
        if text and text not in seen:
            seen.add(text)
            items.append((text, qty))

    for s in services:
        code = (_get(s, 'code') or '').strip()
        if code == PACKAGE_CODE:
            for part in PACKAGE_CONTENT:
                add(SERVICE_TEXTS[part])
            continue
        full_text = SERVICE_TEXTS.get(code)
        if full_text:
            add(full_text)
        else:
            add(_get(s, 'name') or '', _get(s, 'qty'))
    return items
